export async function consumeSweepCommand(): Promise<"start" | "stop" | null> {
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    const current = await client.query<{ sweep_requested_at: Date | null; sweep_stop_requested: boolean }>(
      "SELECT sweep_requested_at, sweep_stop_requested FROM scan_state WHERE id = 1 FOR UPDATE",
    );
    const row = current.rows[0];
    if (!row?.sweep_requested_at && !row?.sweep_stop_requested) {
      await client.query("COMMIT");
      return null;
    }
    const command = row.sweep_stop_requested ? "stop" : "start";
    await client.query("UPDATE scan_state SET sweep_requested_at = NULL, sweep_stop_requested = FALSE WHERE id = 1");
    await client.query("COMMIT");
    return command;
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

export type RemoteScan = {
  running: boolean;
  scanned: number;
  total: number;
  errors: number;
  current: string[];
  startedAt: string | null;
  finishedAt: string | null;
  phase: "saved" | "refresh" | "initial";
};

export async function getRemoteScan(fallbackTotal: number): Promise<RemoteScan> {
  const result = await getPool().query<{
    running: boolean;
    sweep_scanned: number | null;
    sweep_total: number | null;
    sweep_errors: number | null;
    sweep_phase: string | null;
    sweep_current: string | null;
    sweep_started_at: Date | null;
    sweep_finished_at: Date | null;
  }>(
    `SELECT
       (sweep_owner IS NOT NULL AND sweep_heartbeat > NOW() - INTERVAL '90 seconds') AS running,
       sweep_scanned, sweep_total, sweep_errors, sweep_phase, sweep_current,
       sweep_started_at, sweep_finished_at
     FROM scan_state WHERE id = 1`,
  );
  const row = result.rows[0];
  const running = Boolean(row?.running);
  const total = row?.sweep_total && row.sweep_total > 0 ? row.sweep_total : fallbackTotal;
  const phase = row?.sweep_phase === "refresh" || row?.sweep_phase === "initial" ? row.sweep_phase : "saved";
  const scanned = running ? (row?.sweep_scanned ?? 0) : phase === "saved" ? total : (row?.sweep_scanned ?? 0);
  return {
    running,
    scanned,
    total,
    errors: row?.sweep_errors ?? 0,
    current: row?.sweep_current ? row.sweep_current.split(",").filter(Boolean) : [],
    startedAt: row?.sweep_started_at ? row.sweep_started_at.toISOString() : null,
    finishedAt: row?.sweep_finished_at ? row.sweep_finished_at.toISOString() : null,
    phase: running ? "refresh" : phase,
  };
}

