export async function addPosition(optionSymbol: string): Promise<"added" | "exists" | "missing"> {
  if (!isPositionSymbol(optionSymbol)) return "missing";
  const db = getPool();
  const found = await db.query<{
    option_symbol: string;
    ticker: string;
    option_type: string;
    strike: number | null;
    expiration: string | null;
    open_interest: number | null;
    volume: number | null;
    last: number | null;
  }>(
    `SELECT option_symbol, ticker, option_type, strike, expiration, open_interest, volume, last
     FROM unusual_contracts WHERE option_symbol = $1`,
    [optionSymbol],
  );
  const row = found.rows[0];
  if (!row) return "missing";
  const inserted = await db.query(
    `INSERT INTO watched_positions (option_symbol, ticker, option_type, strike, expiration)
     VALUES ($1, $2, $3, $4, $5)
     ON CONFLICT (option_symbol) DO NOTHING
     RETURNING option_symbol`,
    [row.option_symbol, row.ticker, row.option_type, row.strike, row.expiration],
  );
  if ((inserted.rowCount ?? 0) === 0) return "exists";
  await db.query(
    `INSERT INTO watched_snapshots (option_symbol, open_interest, volume, last) VALUES ($1, $2, $3, $4)`,
    [row.option_symbol, row.open_interest, row.volume, row.last],
  );
  return "added";
}

export async function removePosition(optionSymbol: string): Promise<boolean> {
  if (!isPositionSymbol(optionSymbol)) return false;
  const result = await getPool().query("DELETE FROM watched_positions WHERE option_symbol = $1", [optionSymbol]);
  return (result.rowCount ?? 0) > 0;
}

export async function recordWatchProgress(quotes: WatchQuote[]): Promise<void> {
  if (quotes.length === 0) return;
  await getPool().query(
    `INSERT INTO watched_snapshots (option_symbol, open_interest, volume, last)
     SELECT v.option_symbol, v.open_interest, v.volume, v.last
     FROM unnest($1::text[], $2::int[], $3::int[], $4::float8[]) AS v(option_symbol, open_interest, volume, last)
     JOIN watched_positions p ON p.option_symbol = v.option_symbol
     LEFT JOIN LATERAL (
       SELECT open_interest, volume, last, captured_at
       FROM watched_snapshots s
       WHERE s.option_symbol = v.option_symbol
       ORDER BY s.captured_at DESC
       LIMIT 1
     ) prev ON true
     WHERE prev.captured_at IS NULL
        OR prev.open_interest IS DISTINCT FROM v.open_interest
        OR prev.volume IS DISTINCT FROM v.volume
        OR prev.last IS DISTINCT FROM v.last
        OR prev.captured_at < NOW() - INTERVAL '6 hours'`,
    [
      quotes.map((quote) => quote.optionSymbol),
      quotes.map((quote) => quote.openInterest),
      quotes.map((quote) => quote.volume),
      quotes.map((quote) => quote.last),
    ],
  );
}

export async function listPositions(): Promise<PositionView[]> {
  const db = getPool();
  const positions = await db.query<{
    option_symbol: string;
    ticker: string;
    option_type: string;
    strike: number | null;
    expiration: string | null;
    added_at: string;
    still_listed: boolean;
  }>(
    `SELECT p.option_symbol, p.ticker, p.option_type, p.strike, p.expiration,
            to_char(p.added_at AT TIME ZONE 'America/New_York', 'YYYY-MM-DD"T"HH24:MI:SS') AS added_at,
            EXISTS (SELECT 1 FROM unusual_contracts u WHERE u.option_symbol = p.option_symbol) AS still_listed
     FROM watched_positions p
     ORDER BY p.added_at DESC`,
  );
  if (positions.rows.length === 0) return [];
  const symbols = positions.rows.map((row) => row.option_symbol);
  const snaps = await db.query<{
    option_symbol: string;
    captured_at: string;
    open_interest: number | null;
    volume: number | null;
    last: number | null;
    rn_asc: number;
    rn_desc: number;
  }>(
    `SELECT option_symbol, captured_at, open_interest, volume, last, rn_asc, rn_desc
     FROM (
       SELECT option_symbol,
              to_char(captured_at AT TIME ZONE 'America/New_York', 'YYYY-MM-DD"T"HH24:MI:SS') AS captured_at,
              open_interest, volume, last,
              row_number() OVER (PARTITION BY option_symbol ORDER BY captured_at ASC) AS rn_asc,
              row_number() OVER (PARTITION BY option_symbol ORDER BY captured_at DESC) AS rn_desc
       FROM watched_snapshots
       WHERE option_symbol = ANY($1::text[])
     ) s
     WHERE rn_asc = 1 OR rn_desc <= 24`,
    [symbols],
  );
  const bySymbol = new Map<string, typeof snaps.rows>();
  for (const snap of snaps.rows) {
    const list = bySymbol.get(snap.option_symbol) ?? [];
    list.push(snap);
    bySymbol.set(snap.option_symbol, list);
  }
  return positions.rows.map((row) => {
    const history = bySymbol.get(row.option_symbol) ?? [];
    const first = history.find((snap) => Number(snap.rn_asc) === 1) ?? null;
    const latest = history.find((snap) => Number(snap.rn_desc) === 1) ?? first;
    const readings = history
      .filter((snap) => Number(snap.rn_desc) <= 24 || Number(snap.rn_asc) === 1)
      .sort((a, b) => a.captured_at.localeCompare(b.captured_at))
      .filter((snap, index, all) => all.findIndex((item) => item.captured_at === snap.captured_at) === index)
      .map((snap) => ({
        capturedAt: snap.captured_at,
        openInterest: snap.open_interest,
        volume: snap.volume,
        last: snap.last,
      }));
    return {
      optionSymbol: row.option_symbol,
      ticker: row.ticker,
      optionType: row.option_type === "put" ? "put" : "call",
      strike: row.strike,
      expiration: row.expiration,
      addedAt: row.added_at,
      stillListed: row.still_listed,
      openInterest: level(first?.open_interest ?? null, latest?.open_interest ?? null),
      volume: level(first?.volume ?? null, latest?.volume ?? null),
      last: level(first?.last ?? null, latest?.last ?? null),
      readings,
    };
  });
}

function level(first: number | null, latest: number | null): PositionLevel {
  return { first, latest, move: progressMove(first, latest) };
}

const SORTS: Record<string, string> = {
  occurredAt: "occurred_at",
  ticker: "ticker",
  optionType: "option_type",
  strike: "strike",
  expiration: "expiration",
  dte: "dte",
  volume: "volume",
  openInterest: "open_interest",
  volumeOiRatio: "volume_oi_ratio",
  estimatedPremium: "estimated_premium",
  bid: "bid",
  ask: "ask",
  last: "last",
  selectionScore: '"selectionScore"',
};

export async function listActivity(query: ActivityQuery): Promise<{ total: number; rows: unknown[]; sort: string }> {
  const sort = SORTS[query.sort] ? query.sort : "occurredAt";
  const column = SORTS[sort] ?? "occurred_at";
  const order = query.order === "ASC" ? "ASC" : "DESC";
  const params: Array<string | number> = [];
  const filters = visibleFilter(params);
  if (query.listing === "sp500") {
    params.push(1);
    filters.clauses.push(`in_sp500 = $${params.length}`);
  } else if (query.listing === "nasdaq") {
    params.push(1);
    filters.clauses.push(`in_nasdaq = $${params.length}`);
  }
  if (query.q) {
    params.push(query.q);
    filters.clauses.push(`ticker = $${params.length}`);
  }
  if (query.quiet) {
    filters.clauses.push(`(volume_oi_ratio IS NULL OR volume_oi_ratio < ${DAY_UNUSUAL_VOLUME_RATIO})`);
  }
  const where = filters.clauses.length ? `WHERE ${filters.clauses.join(" AND ")}` : "";
  const db = getPool();
  const total = await db.query<{ count: string }>(`SELECT COUNT(*)::int AS count FROM unusual_contracts ${where}`, params);
  params.push(query.pageSize, (query.page - 1) * query.pageSize);
  const rows = await db.query(
    `SELECT id, option_symbol AS "optionSymbol", occurred_at AS "occurredAt", ticker,
            option_type AS "optionType", direction, strike, expiration, dte, volume,
            open_interest AS "openInterest", volume_oi_ratio AS "volumeOiRatio",
            estimated_premium AS "estimatedPremium", bid, ask, last,
            underlying_price AS "underlyingPrice", source,
            ${selectionScoreSql} AS "selectionScore",
            (volume_oi_ratio >= ${DAY_UNUSUAL_VOLUME_RATIO}) AS "dayUnusual"
     FROM unusual_contracts
     ${where}
     ORDER BY CASE WHEN volume_oi_ratio >= ${DAY_UNUSUAL_VOLUME_RATIO} THEN 0 ELSE 1 END,
              CASE WHEN volume_oi_ratio >= ${DAY_UNUSUAL_VOLUME_RATIO} THEN volume_oi_ratio END DESC NULLS LAST,
              ${column} ${order} NULLS LAST, ticker ASC
     LIMIT $${params.length - 1} OFFSET $${params.length}`,
    params,
  );
  return { total: Number(total.rows[0]?.count ?? 0), rows: rows.rows, sort };
}

export async function tickerFlow(ticker: string): Promise<{
  ticker: string;
  underlyingPrice: number | null;
  weekly: ReturnType<typeof summarizeFlow>["weekly"];
  monthly: ReturnType<typeof summarizeFlow>["monthly"];
}> {
  const today = todayInNewYork();
  const oldest = plusMonths(today, -6);
  const result = await getPool().query<{
    optionType: "call" | "put";
    expiration: string;
    estimatedPremium: number | null;
    underlyingPrice: number | null;
  }>(
    `SELECT option_type AS "optionType", expiration, estimated_premium AS "estimatedPremium",
            underlying_price AS "underlyingPrice"
     FROM unusual_contracts
     WHERE ticker = $1
       AND estimated_premium >= $2
       AND open_interest > 0
       AND expiration >= $3
       AND occurred_at IS NOT NULL
       AND substr(occurred_at, 1, 10) >= $4`,
    [ticker, MIN_UNUSUAL_SIZE, today, oldest],
  );
  const summary = summarizeFlow(result.rows, today);
  const underlyingPrice = result.rows.reduce<number | null>((price, row) => price ?? row.underlyingPrice, null);
  return { ticker, underlyingPrice, ...summary };
}

function visibleFilter(params: Array<string | number>): { where: string; clauses: string[]; params: Array<string | number> } {
  const today = todayInNewYork();
  const oldest = plusMonths(today, -6);
  params.push(MIN_UNUSUAL_SIZE, today, oldest);
  const clauses = [
    `estimated_premium >= $${params.length - 2}`,
    "open_interest > 0",
    `expiration >= $${params.length - 1}`,
    "occurred_at IS NOT NULL",
    `substr(occurred_at, 1, 10) >= $${params.length}`,
  ];
  return { where: `WHERE ${clauses.join(" AND ")}`, clauses, params };
}
